"""Medication-safety (prescription check) endpoint (API v1).

Deterministic rule-engine check of one candidate medication against the
patient's active regimen and recorded allergies. The optional LLM
explanation is only a rendering of the deterministic warnings — the model
never invents, alters, or suppresses a warning (spec §11).
"""

import logging

from fastapi import APIRouter, Depends, HTTPException, status
from sqlalchemy import select
from sqlalchemy.orm import Session, selectinload

from app.api.v1.dependencies import patient_from_id
from app.db.session import get_db
from app.models import Allergy, Medication, Patient, PatientMedication
from app.models.enums import MedicationStatus
from app.schemas.medication_safety import (
    MedicationSafetyCheckRequest,
    MedicationSafetyCheckResponse,
    SafetyWarning,
)
from app.services import ai
from app.services.medication_safety import (
    check_medication_safety,
    class_labels,
    load_rules_kb,
    now_utc,
)

router = APIRouter(tags=["medication-safety"])

logger = logging.getLogger(__name__)

MEDICATION_NOT_FOUND_DETAIL = "دارو در فهرست داروها یافت نشد."
EXPLANATION_DISCLAIMER = (
    "این توضیح توسط مدل زبانی و صرفاً برای فهم بهتر هشدارهای قطعیِ قاعده‌محور "
    "تولید شده است؛ خودِ هشدارها مستقل از مدل و قابل‌ردیابی با شناسهٔ قاعده هستند."
)

_EXPLAIN_SYSTEM_PROMPT = (
    "You explain deterministic medication-safety warnings to a physician in "
    "Persian. You receive the exact warnings (already in Persian) produced by "
    "a rule engine. Rules: restate and briefly clarify ONLY these warnings; "
    "never add new warnings, drug claims, dosing advice, or medical facts; "
    "keep it under 180 words; end with a reminder that the physician makes "
    "the final decision."
)


@router.post(
    "/patients/{patient_id}/medications/check",
    response_model=MedicationSafetyCheckResponse,
    summary="Deterministic prescription-safety check for one candidate medication",
    description=(
        "Checks a candidate medication (by `medication_id` or free-text "
        "`medication_name`) against the patient's **active** medications and "
        "recorded allergies, using a versioned local rules knowledge base "
        "(drug–drug interactions, allergy conflicts, duplicate therapy). "
        "Warnings are deterministic and cite their rule id — they are never "
        "generated by an AI model. `explain=true` additionally asks the "
        "configured LLM to *explain* the warnings in Persian (never to "
        "produce them); if the provider is unavailable the warnings are "
        "still returned with `explanation=null`."
    ),
    responses={
        status.HTTP_404_NOT_FOUND: {"description": "بیمار یا دارو یافت نشد"},
        status.HTTP_422_UNPROCESSABLE_ENTITY: {"description": "ورودی نامعتبر"},
    },
)
def check_patient_medication(
    patient_id: int,
    payload: MedicationSafetyCheckRequest,
    patient: Patient = Depends(patient_from_id),
    db: Session = Depends(get_db),
) -> MedicationSafetyCheckResponse:
    # resolve the candidate's display name(s)
    if payload.medication_id is not None:
        medication = db.get(Medication, payload.medication_id)
        if medication is None:
            raise HTTPException(
                status_code=status.HTTP_404_NOT_FOUND,
                detail=MEDICATION_NOT_FOUND_DETAIL,
            )
        candidate_name = medication.name
    else:
        candidate_name = (payload.medication_name or "").strip()

    # active regimen: check the catalog name AND the generic name
    active_records = db.scalars(
        select(PatientMedication)
        .where(
            PatientMedication.patient_id == patient.id,
            PatientMedication.status == MedicationStatus.active,
        )
        .options(selectinload(PatientMedication.medication))
    ).all()
    active_names = [
        name
        for record in active_records
        for name in (record.medication.name, record.medication.generic_name)
        if name
    ]

    allergens = db.scalars(
        select(Allergy.allergen).where(Allergy.patient_id == patient.id)
    ).all()

    result = check_medication_safety(
        candidate_name=candidate_name,
        active_medication_names=list(active_names),
        allergen_names=list(allergens),
    )

    explanation: str | None = None
    if payload.explain and result.warnings:
        explanation = _explain_warnings(result.warnings)

    return MedicationSafetyCheckResponse(
        patient_id=patient.id,
        candidate_name=candidate_name,
        candidate_class_labels=class_labels(result.candidate_classes),
        candidate_covered=bool(result.candidate_classes),
        warnings=result.warnings,
        rules_version=load_rules_kb().version,
        checked_at=now_utc(),
        explanation=explanation,
        explanation_disclaimer=EXPLANATION_DISCLAIMER if explanation else None,
    )


def _explain_warnings(warnings: list[SafetyWarning]) -> str | None:
    """Optional LLM explanation — best effort, never fails the check."""
    import json

    payload = [
        {
            "rule_id": warning.rule_id,
            "type": warning.warning_type,
            "severity": warning.severity,
            "title": warning.title,
            "detail": warning.detail,
            "involved": warning.involved,
        }
        for warning in warnings
    ]
    try:
        provider = ai.get_provider()
        return provider.complete(
            system=_EXPLAIN_SYSTEM_PROMPT,
            user=json.dumps(payload, ensure_ascii=False),
        ).strip()
    except Exception as error:  # noqa: BLE001 — explanation must never break safety
        logger.warning(
            "medication-safety LLM explanation skipped: %s: %s",
            type(error).__name__,
            error,
        )
        return None
